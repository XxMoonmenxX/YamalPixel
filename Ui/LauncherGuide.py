class LauncherGuide(QDialog):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle('Гайд по лаунчеру')
        self.resize(1050, 720)
        self.setMinimumSize(800, 550)
        self.setStyleSheet('''QDialog { background: #102033; color: #eaf2fa; font-family: 'Segoe UI'; }
            QLineEdit, QListWidget, QTextBrowser { background: #0b192a; color: #eaf2fa;
                border: 1px solid #38516a; border-radius: 8px; padding: 10px; font-size: 14px; }
            QListWidget::item { padding: 10px; } QListWidget::item:selected { background: #28556a; }
            QPushButton { background: #28556a; color: white; padding: 9px 20px; border-radius: 7px; }''')
        layout = QVBoxLayout(self)
        self.search = QLineEdit()
        self.search.setPlaceholderText('Поиск по гайду: сборка, память, шейдеры…')
        self.search.textChanged.connect(self.filter_pages)
        layout.addWidget(self.search)
        splitter = QSplitter(Qt.Orientation.Horizontal)
        self.sections = QListWidget()
        self.sections.setMinimumWidth(260)
        self.sections.setWordWrap(True)
        self.sections.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        self.sections.addItems([title for title, _ in GUIDE_PAGES])
        self.sections.currentRowChanged.connect(self.show_page)
        self.browser = QTextBrowser()
        self.browser.setOpenExternalLinks(False)
        splitter.addWidget(self.sections)
        splitter.addWidget(self.browser)
        splitter.setSizes([310, 710])
        layout.addWidget(splitter, 1)
        bottom = QHBoxLayout()
        bottom.addStretch()
        close = QPushButton('Закрыть')
        close.clicked.connect(self.accept)
        bottom.addWidget(close)
        layout.addLayout(bottom)
        self.sections.setCurrentRow(0)

    def show_page(self, index):
        if 0 <= index < len(GUIDE_PAGES):
            self.browser.setHtml('<style>p,li { line-height:1.5; } h2 { color:#68e0cc; }</style>'
                                 + GUIDE_PAGES[index][1])

    def filter_pages(self, text):
        query = text.strip().casefold()
        visible = []
        for index, (title, body) in enumerate(GUIDE_PAGES):
            matches = query in (title + ' ' + body).casefold()
            self.sections.item(index).setHidden(not matches)
            if matches:
                visible.append(index)
        if visible:
            self.sections.setCurrentRow(visible[0])
            self.show_page(visible[0])
        else:
            self.browser.setHtml('<h2>Раздел не найден</h2><p>Попробуй другое слово или очисти поиск.</p>')
